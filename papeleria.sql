-- Si vuelves a correr el script, borra las tablas en orden (por las llaves foráneas)
DROP TABLE IF EXISTS detalle_venta;
DROP TABLE IF EXISTS ventas;
DROP TABLE IF EXISTS productos;

-- -------------------------------------------------------------
-- Productos
-- -------------------------------------------------------------
CREATE TABLE productos (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(100)   NOT NULL,
    precio  NUMERIC(10, 2) NOT NULL CHECK (precio > 0),
    stock   INTEGER        NOT NULL DEFAULT 0 CHECK (stock >= 0)
);

-- -------------------------------------------------------------
-- Ventas (encabezado)
-- -------------------------------------------------------------
CREATE TABLE ventas (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha  TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total  NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (total >= 0)
);

-- -------------------------------------------------------------
-- Detalle de venta: qué productos se vendieron en cada venta
-- -------------------------------------------------------------
CREATE TABLE detalle_venta (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id         BIGINT         NOT NULL,
    producto_id      BIGINT         NOT NULL,
    cantidad         INTEGER        NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(10, 2) NOT NULL CHECK (precio_unitario > 0),
    subtotal         NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),

    -- Si se borra la venta, se borran sus renglones
    CONSTRAINT fk_detalle_venta FOREIGN KEY (venta_id)
        REFERENCES ventas (id) ON DELETE CASCADE,

    -- No se puede borrar un producto que ya se vendió
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id)
        REFERENCES productos (id) ON DELETE RESTRICT
);

CREATE INDEX idx_detalle_venta_venta    ON detalle_venta (venta_id);
CREATE INDEX idx_detalle_venta_producto ON detalle_venta (producto_id);

