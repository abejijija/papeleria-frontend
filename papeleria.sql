    (2, 3, 1, 650.00, 650.00),
    (2, 4, 1, 320.00, 320.00);

-- El stock refleja las ventas de ejemplo
UPDATE productos SET stock = stock - 3 WHERE id = 1;   -- cuaderno:    60 -> 57
UPDATE productos SET stock = stock - 2 WHERE id = 2;   -- bolígrafos:  40 -> 38
UPDATE productos SET stock = stock - 1 WHERE id = 3;   -- mochila:     10 -> 9
